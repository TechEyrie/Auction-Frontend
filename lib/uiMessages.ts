export const MESSAGES: Record<UiLang, Record<MessageKey, string>> = { en: EN, ar: AR };

/** Look up a message and fill `{placeholders}`. Falls back to English, then to the key itself. */
export function translate(lang: UiLang, key: MessageKey, vars?: Record<string, string | number>): string {
  const template = MESSAGES[lang][key] ?? MESSAGES.en[key] ?? key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) => (name in vars ? String(vars[name]) : match));
}

/** Localised listing-method name, falling back to the raw value for unknown methods. */
export function methodLabel(lang: UiLang, method: string): string {
  const key = `method.${method}` as MessageKey;
  return key in EN ? translate(lang, key) : method;
}

/** Localised condition name, falling back to the raw value with underscores spaced out. */
export function conditionLabel(lang: UiLang, condition: string): string {
  const key = `condition.${condition}` as MessageKey;
  return key in EN ? translate(lang, key) : condition.replace('_', ' ');
}
