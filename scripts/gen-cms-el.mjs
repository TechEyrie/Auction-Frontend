const SD = ' — short description';

function labelToAr(en, key) {
  if (MANUAL_AR[en]) return MANUAL_AR[en];
  if (key in MESSAGES.en && MESSAGES.en[key] === en) return MESSAGES.ar[key];
  if (en.endsWith(SD)) {
    const base = en.slice(0, -SD.length);
    const titleKey = key.replace(/\.desc$/, '.title');
    if (titleKey in MESSAGES.ar) return `${MESSAGES.ar[titleKey]}${' — وصف مختصر'}`;
    if (base in MANUAL_AR) return `${MANUAL_AR[base]} — وصف مختصر`;
    if (base in MESSAGES.ar) return `${MESSAGES.ar[base]} — وصف مختصر`;
    const baseMk = Object.keys(MESSAGES.en).find((k) => MESSAGES.en[k] === base);
    if (baseMk) return `${MESSAGES.ar[baseMk]} — وصف مختصر`;
  }
  const mk = Object.keys(MESSAGES.en).find((k) => MESSAGES.en[k] === en);
  if (mk) return MESSAGES.ar[mk];
  return en;
}

